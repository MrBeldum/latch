fn random(state: &mut u64) -> u64 {
    *state ^= *state << 13;
    *state ^= *state >> 7;
    *state ^= *state << 17;
    *state
}

#[test]
fn one_hundred_thousand_malformed_access_units_never_panic_and_recover() {
    let units = access_units(SEED);
    let idr = units[0];
    let mut decoder = Decoder::new();
    let mut rng = 0x6c61746368353031u64;
    let mut errors = 0;
    let cases: usize = std::env::var("LATCH_ROBUSTNESS_CASES")
        .or_else(|_| std::env::var("ROBUSTNESS_CASES"))
        .or_else(|_| std::env::var("LATCH_ROBUSTNESS_COUNT"))
        .or_else(|_| std::env::var("ROBUSTNESS_COUNT"))
        .ok()
        .and_then(|v| v.parse().ok())
        .or_else(|| {
            if std::env::var_os("LATCH_ROBUSTNESS_FULL").is_some()
                || std::env::var_os("ROBUSTNESS_FULL").is_some()
            {
                Some(100_000)
            } else {
                None
            }
        })
        .unwrap_or(10_000);
    for case in 0..cases {
        assert!(decoder.decode(idr).unwrap().is_some());
        let source = units[(random(&mut rng) as usize) % units.len()];
        let mut data = match case % 3 {
            0 => source[..random(&mut rng) as usize % source.len()].to_vec(),
            1 => {
                let mut data = source.to_vec();
                for _ in 0..1 + random(&mut rng) % 4 {
                    let i = random(&mut rng) as usize % data.len();
                    data[i] ^= 1 << (random(&mut rng) % 8);
                }
                data
            }
            _ => {
                let n = random(&mut rng) as usize % 512;
                (0..n).map(|_| random(&mut rng) as u8).collect::<Vec<_>>()
            }
        };
        if case % 6 == 5 {
            let mut prefix = Vec::new();
            for nal in nal_units(idr)
                .into_iter()
                .filter(|n| matches!(n[0] & 31, 7 | 8))
            {
                prefix.extend_from_slice(&[0, 0, 1]);
                prefix.extend_from_slice(nal);
            }
            prefix.extend_from_slice(&[0, 0, 1, 0x65]);
            prefix.append(&mut data);
            data = prefix;
        }
        if decoder.decode(&data).is_err() {
            errors += 1;
            assert!(
                decoder.decode(units[1]).is_err(),
                "case {case}: references survived corruption"
            );
            assert!(
                decoder.decode(idr).unwrap().is_some(),
                "case {case}: IDR recovery"
            );
        }
    }
    eprintln!("{cases} fixed-seed cases: {errors} errors returned, zero panics; IDR recovery verified after each error");
}

#[test]
fn missing_references_and_reset_are_explicit() {
    let units = access_units(SEED);
    let mut decoder = Decoder::new();
    let mut params = Vec::new();
    for nal in nal_units(units[0])
        .into_iter()
        .filter(|n| matches!(n[0] & 31, 7 | 8))
    {
        params.extend_from_slice(&[0, 0, 1]);
        params.extend_from_slice(nal);
    }
    assert!(decoder.decode(&params).unwrap().is_none());
    assert_eq!(
        decoder.decode(units[1]).unwrap_err(),
        CodecError::MissingReference
    );
    assert!(decoder.decode(units[0]).unwrap().is_some());
    assert!(decoder.decode(units[1]).unwrap().is_some());
    decoder.reset();
    assert!(decoder.decode(units[0]).unwrap().is_some());
}
