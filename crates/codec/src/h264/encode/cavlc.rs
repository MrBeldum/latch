pub(super) fn write(bits: &mut Bits, coeff: &[i32], nc: i32) -> u8 {
    if coeff.iter().all(|&v| v == 0) {
        let (len, code) = if nc < 0 {
            (CHROMA_DC_COEFF_TOKEN_LEN[0], CHROMA_DC_COEFF_TOKEN_BITS[0])
        } else {
            let tab = if nc < 2 {
                0
            } else if nc < 4 {
                1
            } else if nc < 8 {
                2
            } else {
                3
            };
            (COEFF_TOKEN_LEN[tab][0], COEFF_TOKEN_BITS[tab][0])
        };
        bits.put(code as u32, len as usize);
        return 0;
    }
    let mut levels = [0i32; 16];
    let mut positions = [0usize; 16];
    let mut count = 0;
    for (i, &v) in coeff.iter().enumerate() {
        if v != 0 {
            levels[count] = v;
            positions[count] = i;
            count += 1;
        }
    }
    let mut trailing = 0;
    while trailing < count.min(3) && levels[count - 1 - trailing].abs() == 1 {
        trailing += 1;
    }
    let index = count * 4 + trailing;
    let (len, code) = if nc < 0 {
        (
            CHROMA_DC_COEFF_TOKEN_LEN[index],
            CHROMA_DC_COEFF_TOKEN_BITS[index],
        )
    } else {
        let tab = if nc < 2 {
            0
        } else if nc < 4 {
            1
        } else if nc < 8 {
            2
        } else {
            3
        };
        (COEFF_TOKEN_LEN[tab][index], COEFF_TOKEN_BITS[tab][index])
    };
    bits.put(code as u32, len as usize);
    if count == 0 {
        return 0;
    }
    for i in 0..trailing {
        bits.bit(levels[count - 1 - i] < 0);
    }
    let mut suffix = usize::from(count > 10 && trailing < 3);
    for i in trailing..count {
        let level = levels[count - 1 - i];
        let mut code = (2 * level.abs() - if level > 0 { 2 } else { 1 }) as u32;
        if i == trailing && trailing < 3 {
            code -= 2;
        }
        let prefix = code >> suffix;
        if prefix < 14 {
            bits.put(1, prefix as usize + 1);
            bits.put(code & ((1 << suffix) - 1), suffix);
        } else if suffix == 0 && code < 30 {
            bits.put(1, 15);
            bits.put(code - 14, 4);
        } else if suffix > 0 && prefix == 14 {
            bits.put(1, 15);
            bits.put(code & ((1 << suffix) - 1), suffix);
        } else {
            code -= 15 << suffix;
            if suffix == 0 {
                code -= 15;
            }
            let mut prefix = 15;
            while code >= (1 << (prefix - 3)) {
                code -= 1 << (prefix - 3);
                prefix += 1;
            }
            bits.put(1, prefix + 1);
            bits.put(code, prefix - 3);
        }
        if suffix == 0 {
            suffix = 1;
        }
        if level.abs() > (3 << (suffix - 1)) && suffix < 6 {
            suffix += 1;
        }
    }
    let mut zeros = positions[count - 1] + 1 - count;
    if count < coeff.len() {
        let (len, code) = if nc < 0 {
            (
                CHROMA_DC_TOTAL_ZEROS_LEN[count - 1][zeros],
                CHROMA_DC_TOTAL_ZEROS_BITS[count - 1][zeros],
            )
        } else {
            (
                TOTAL_ZEROS_LEN[count - 1][zeros],
                TOTAL_ZEROS_BITS[count - 1][zeros],
            )
        };
        bits.put(code as u32, len as usize);
    }
    for i in (1..count).rev() {
        if zeros == 0 {
            break;
        }
        let run = positions[i] - positions[i - 1] - 1;
        let tab = zeros.min(7) - 1;
        bits.put(RUN_BITS[tab][run] as u32, RUN_LEN[tab][run] as usize);
        zeros -= run;
    }
    count as u8
}
